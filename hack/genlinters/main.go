// Command genlinters writes internal/known/linters_gen.go from melange's
// linter registry, which melange does not export. Run via go generate.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

var entry = regexp.MustCompile(`(?s)\n\t"([^"]+)": \{\n(.*?)\n\t\},`)
var explain = regexp.MustCompile(`Explain:\s+"((?:[^"\\]|\\.)*)"`)
var behavior = regexp.MustCompile(`defaultBehavior:\s+(\w+)`)

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "chainguard.dev/melange").Output()
	if err != nil {
		log.Fatal(err)
	}
	src, err := os.ReadFile(filepath.Join(strings.TrimSpace(string(out)), "pkg", "linter", "linter.go"))
	if err != nil {
		log.Fatal(err)
	}
	start := bytes.Index(src, []byte("var linterMap = map[string]linter{"))
	if start < 0 {
		log.Fatal("linterMap not found")
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by hack/genlinters from melange's pkg/linter. DO NOT EDIT.\n\npackage known\n\n")
	b.WriteString("// Linters are melange's package linters, for checks.disabled.\nvar Linters = []Linter{\n")
	n := 0
	for _, m := range entry.FindAllSubmatch(src[start:], -1) {
		body := m[2]
		e := explain.FindSubmatch(body)
		bh := behavior.FindSubmatch(body)
		if e == nil || bh == nil {
			continue
		}
		fmt.Fprintf(&b, "\t{Name: %q, Explain: \"%s\", Default: %q},\n", m[1], e[1], strings.ToLower(string(bh[1])))
		n++
	}
	b.WriteString("}\n")
	if n < 10 {
		log.Fatalf("only found %d linters; has melange's linter.go changed format?", n)
	}
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("linters_gen.go", formatted, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %d linters", n)
}
